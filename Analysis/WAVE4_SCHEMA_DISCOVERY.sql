-- SCHEMA DISCOVERY for NEW COLUMNS
-- Run these queries to understand FirstName and Version columns

USE MMGTDB2A
GO

PRINT '=== APPLICATIONS.FirstName Column Definition ==='
SELECT 
	COLUMN_NAME, 
	DATA_TYPE, 
	CHARACTER_MAXIMUM_LENGTH,
	IS_NULLABLE, 
	COLUMN_DEFAULT,
	COLUMNPROPERTY(OBJECT_ID('Applications'), COLUMN_NAME, 'IsIdentity') AS IsIdentity
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'Applications' AND COLUMN_NAME LIKE '%FirstName%'

PRINT ''
PRINT '=== APPLICATIONS all columns (for context) ==='
SELECT COLUMN_NAME, DATA_TYPE, IS_NULLABLE, COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'Applications'
ORDER BY ORDINAL_POSITION

PRINT ''
PRINT '=== APPLICATIONDOCUMENTS.Version Column Definition ==='
SELECT 
	COLUMN_NAME, 
	DATA_TYPE,
	IS_NULLABLE, 
	COLUMN_DEFAULT,
	COLUMNPROPERTY(OBJECT_ID('ApplicationDocuments'), COLUMN_NAME, 'IsIdentity') AS IsIdentity
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'ApplicationDocuments' AND COLUMN_NAME LIKE '%Version%'

PRINT ''
PRINT '=== APPLICATIONDOCUMENTS all columns (for context) ==='
SELECT COLUMN_NAME, DATA_TYPE, IS_NULLABLE, COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'ApplicationDocuments'
ORDER BY ORDINAL_POSITION

