-- Check target schema for Applications and ApplicationDocuments
USE MMGTDB2A
GO

-- Applications all columns
SELECT 
	COLUMN_NAME, 
	DATA_TYPE, 
	CHARACTER_MAXIMUM_LENGTH,
	IS_NULLABLE, 
	COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'Applications'
ORDER BY ORDINAL_POSITION
GO

-- ApplicationDocuments all columns
SELECT 
	COLUMN_NAME, 
	DATA_TYPE, 
	CHARACTER_MAXIMUM_LENGTH,
	IS_NULLABLE, 
	COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'ApplicationDocuments'
ORDER BY ORDINAL_POSITION
GO

